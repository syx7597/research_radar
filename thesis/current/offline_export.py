#!/usr/bin/env python3
"""Export domain preparation tables from public aggregates, without private QA."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
FILES = {
    "freeze": "results/radar_domain/frozen_20261107/summary.json",
    "audit": "results/radar_domain/frozen_20261107/cpu_audit.json",
    "tokens": "results/radar_domain/frozen_20261107/token_preflight.json",
    "recovery": "results/radar_domain/recovery_contract_20261107/summary.json",
    "sources": "artifacts/thesis_direction_review/radar_new_sources_20261107/summary.json",
    "review": "artifacts/thesis_direction_review/radar_new_sources_review_20261107/review_summary.safe.json",
    "dev": "results/radar_domain/programs_dev_20261107/summary.json",
    "holdout": "results/radar_domain/holdout_programs_20261107/summary.json",
    "case": "results/radar_domain/programs_dev_20261107/development_case.json",
    "scoring_revision": "results/radar_domain/frozen_20261107/scoring_revision.json",
}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def build():
    docs = {k: json.loads((ROOT / path).read_text()) for k, path in FILES.items()}
    hashes = {path: sha(ROOT / path) for path in FILES.values()}
    assert docs["audit"]["status"] == "passed"
    assert docs["audit"]["manifest"] == docs["freeze"]["freeze_manifest"]
    assert docs["audit"]["scoring_revision"]["sha256"] == hashes[FILES["scoring_revision"]]
    assert docs["tokens"]["reference_trajectories"] == sum(docs["freeze"]["question_counts"].values()) == 708
    assert docs["recovery"]["actual_model_rollouts"] == docs["freeze"]["model_runs"] == 0
    assert docs["review"]["content_consistent_count"] == docs["holdout"]["counts"]["questions"] == 24
    assert docs["recovery"]["all_reference_targets_preserved"] and docs["recovery"]["all_supervised_token_budgets_matched"]
    tex = ["% Generated by offline_export.py from public aggregates. CPU validation, not model evaluation."]
    rows = []

    def value(table, label, source, pointer):
        v = docs[source]
        for key in pointer.strip("/").split("/"):
            v = v[int(key)] if isinstance(v, list) else v[key]
        rows.append({"table": table, "label": label, "value": v, "source": FILES[source], "json_pointer": pointer})
        return v

    def table(name, header, body, align=None):
        tex.extend(["\\newcommand{\\" + name + "}{%", "\\begin{tabular}{" + (align or "l" + "r" * (len(header)-1)) + "}",
                    "\\toprule", " & ".join(header) + r" \\", "\\midrule"])
        tex.extend(" & ".join(map(str, row)) + r" \\" for row in body)
        tex.extend(["\\bottomrule", "\\end{tabular}%", "}"])

    body = []
    for split, label in (("train", "合成训练"), ("dev", "开发"), ("holdout", "新来源评价")):
        body.append([label, *[value("split", label, "freeze", f"/{key}/{split}")
                            for key in ("question_counts", "source_family_counts", "source_record_counts")]])
    table("OfflineSplitTable", ["划分", "题数", "来源组数", "读法数"], body)
    body = []
    names = ["FURUNO DRS4W", "OTT RLS", "smartmicro UMRR-11", "Campbell CS475A"]
    for i, name in enumerate(names):
        pages = value("sources", name, "sources", f"/sources/{i}/pages_one_based")
        body.append([name, ", ".join(map(str, pages)),
                     value("sources", name, "sources", f"/sources/{i}/readings"),
                     value("sources", name, "sources", f"/sources/{i}/questions")])
    table("OfflineSourcesTable", ["资料家族", "PDF页码", "读法", "题数"], body, "llrr")
    body = []
    for split, label in (("train", "训练参考"), ("dev", "开发参考"), ("holdout", "评价参考")):
        n = value("checks", label, "audit", f"/split_results/{split}/references")
        calls = value("checks", label, "audit", f"/split_results/{split}/successful_calls")
        body.append([label, n, calls])
    table("OfflineReplayTable", ["检查范围", "通过程序数", "执行调用总数"], body)
    body = []
    for split, label in (("train", "训练参考"), ("dev", "开发参考"), ("holdout", "评价参考")):
        body.append([label, *[value("tokens", label, "tokens", f"/splits/{split}/{key}") for key in
                            ("max_context_tokens", "max_action_tokens", "max_total_action_tokens")]])
    table("OfflineTokenTable", ["材料", "最长上下文", "最大单步目标", "最大目标总量"], body)
    body = []
    for i, label in enumerate(("扫描器", "处理器、显示器与键盘")):
        lo = value("case", label, "case", f"/rows/{i}/lower_celsius")
        hi = value("case", label, "case", f"/rows/{i}/upper_celsius")
        yes = value("case", label, "case", f"/rows/{i}/within_range_at_minus_20_celsius")
        body.append([label, f"$[{lo:g}, {hi:g}]$", "范围内" if yes else "范围外"])
    table("OfflineTemperatureCaseTable", ["部件组", "温度范围（摄氏度）", "$-20$摄氏度"], body, "lll")
    for command, source, pointer in (
        ("OfflineRecoveryPairs", "recovery", "/fixture_pairs"),
        ("OfflineRecoveryContext", "recovery", "/max_fixture_context_tokens"),
        ("OfflineContextBudget", "tokens", "/registered_runtime_budget/context_tokens"),
        ("OfflineMaxContext", "tokens", "/maximum_context_tokens"),
        ("OfflineReviewedCitations", "review", "/citation_spans_checked")):
        v = value("macros", command, source, pointer)
        tex.append("\\newcommand{\\" + command + "}{" + str(v) + "}")
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator="\n")
    writer.writeheader(); writer.writerows(rows)
    outputs = {"offline_tables.tex": "\n".join(tex) + "\n", "offline_results.csv": buf.getvalue()}
    manifest = {"schema": "radar_offline_thesis_export_v1", "date": "2026-11-07", "rows": len(rows),
                "sources_sha256": hashes, "exporter_sha256": sha(__file__),
                "chapter_sha256": {str(p.relative_to(ROOT)): sha(p) for p in [
                    HERE / "03b_domain_task_data.tex", HERE / "04b_domain_execution.tex", HERE / "06c_domain_preparation.tex"]},
                "outputs_sha256": {n: hashlib.sha256(s.encode()).hexdigest() for n, s in outputs.items()},
                "source_access": "Only allowlisted public aggregate files; no private sources or holdout answers opened",
                "evidence_type": "Source review and CPU execution/token verification", "model_evaluation_runs": 0}
    outputs["offline_evidence_manifest.json"] = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    return outputs


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    outputs = build()
    for name, content in outputs.items():
        path = HERE / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise ValueError("Stale export: " + name)
        else:
            path.write_text(content)
    print(json.dumps({"checked" if args.check else "written": list(outputs)}))


if __name__ == "__main__":
    main()
